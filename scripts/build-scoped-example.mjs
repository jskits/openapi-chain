import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import spawn from 'cross-spawn';
import { compileOpenAPIMetadata } from '../dist/metadata.js';
import { selectedPaths } from '../examples/scoped/scope.ts';

const source = readFileSync(new URL('../examples/scoped/openapi.json', import.meta.url), 'utf8');
const metadata = compileOpenAPIMetadata(JSON.parse(source), { paths: selectedPaths });
assert.deepEqual(Object.keys(metadata.operations).sort(), [...selectedPaths].sort());
const schemaSha256 = createHash('sha256').update(source).digest('hex');
const text = `// Generated by pnpm generate:scoped; do not edit.\nimport type { CompiledOpenAPIMetadata } from '../../src/index.js';\nexport const schemaSha256 = '${schemaSha256}';\nexport const metadata = ${JSON.stringify(metadata)} as unknown as CompiledOpenAPIMetadata;\n`;
const output = new URL('../examples/scoped/metadata.ts', import.meta.url);
const temporary = mkdtempSync(join(tmpdir(), 'openapi-chain-scoped-'));
try {
  const candidate = join(temporary, 'metadata.ts');
  writeFileSync(candidate, text);
  const result = spawn.sync(
    'pnpm',
    ['exec', 'oxfmt', '--config', '.oxfmtrc.json', '--write', candidate],
    { encoding: 'utf8' },
  );
  assert.equal(result.status, 0, result.stdout + result.stderr);
  const formatted = readFileSync(candidate, 'utf8');
  if (process.argv.includes('--check')) {
    assert.equal(
      readFileSync(output, 'utf8'),
      formatted,
      'Scoped metadata is stale. Run pnpm generate:scoped.',
    );
  } else writeFileSync(output, formatted);
  console.log(
    `Scoped metadata verified: ${selectedPaths.length} paths; schema sha256 ${schemaSha256}`,
  );
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
